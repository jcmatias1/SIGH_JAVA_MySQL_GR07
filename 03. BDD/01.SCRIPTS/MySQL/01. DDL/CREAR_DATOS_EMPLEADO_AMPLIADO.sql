USE bd_monster_gr07;
SET NAMES utf8mb4;

/* Table: PETSA_TIPSA (TIPO_SANGRE) */
CREATE TABLE IF NOT EXISTS PETSA_TIPSA
(
   PETSA_CODIGO         CHAR(3) NOT NULL,
   PETSA_DESCRI         VARCHAR(10) NOT NULL,
   PRIMARY KEY (PETSA_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_spanish_ci;

INSERT IGNORE INTO PETSA_TIPSA (PETSA_CODIGO, PETSA_DESCRI) VALUES
 ('A+', 'A+'), ('A-', 'A-'), ('B+', 'B+'), ('B-', 'B-'),
 ('AB+', 'AB+'), ('AB-', 'AB-'), ('O+', 'O+'), ('O-', 'O-');

/* Nuevas columnas de PEEMP_EMPLE (opcionales para no afectar los registros existentes) */
ALTER TABLE PEEMP_EMPLE
   ADD COLUMN IF NOT EXISTS PETSA_CODIGO CHAR(3) NULL AFTER PEESC_CODIGO,
   ADD COLUMN IF NOT EXISTS PEEMP_PESO   DECIMAL(5,2) NULL,
   ADD COLUMN IF NOT EXISTS PEEMP_ESTATU DECIMAL(3,2) NULL;
ALTER TABLE PEEMP_EMPLE
   ADD CONSTRAINT FK_TSA_EMP FOREIGN KEY IF NOT EXISTS (PETSA_CODIGO)
      REFERENCES PETSA_TIPSA (PETSA_CODIGO) ON DELETE RESTRICT ON UPDATE RESTRICT;

/* Table: PENIV_NIVEL (NIVEL_ESTUDIO) */
CREATE TABLE IF NOT EXISTS PENIV_NIVEL
(
   PENIV_CODIGO         CHAR(1) NOT NULL,
   PENIV_DESCRI         VARCHAR(40) NOT NULL,
   PRIMARY KEY (PENIV_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_spanish_ci;

INSERT IGNORE INTO PENIV_NIVEL (PENIV_CODIGO, PENIV_DESCRI) VALUES
 ('1', 'Bachillerato'),
 ('2', 'Técnico / Tecnológico'),
 ('3', 'Tercer nivel'),
 ('4', 'Cuarto nivel');

/* Table: PEACA_ACADE (DATO_ACADEMICO): un empleado puede tener varios títulos */
CREATE TABLE IF NOT EXISTS PEACA_ACADE
(
   PEACA_CODIGO         INT NOT NULL AUTO_INCREMENT,
   PEEMP_CODIGO         CHAR(10) NOT NULL,
   PENIV_CODIGO         CHAR(1) NOT NULL,
   PEACA_INSTIT         VARCHAR(100) NOT NULL,
   PEACA_TITULO         VARCHAR(100) NOT NULL,
   PRIMARY KEY (PEACA_CODIGO),
   CONSTRAINT FK_EMP_ACA FOREIGN KEY (PEEMP_CODIGO) REFERENCES PEEMP_EMPLE (PEEMP_CODIGO)
      ON DELETE RESTRICT ON UPDATE RESTRICT,
   CONSTRAINT FK_NIV_ACA FOREIGN KEY (PENIV_CODIGO) REFERENCES PENIV_NIVEL (PENIV_CODIGO)
      ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_spanish_ci;

/* Table: PEPAR_PAREN (PARENTESCO) */
CREATE TABLE IF NOT EXISTS PEPAR_PAREN
(
   PEPAR_CODIGO         CHAR(1) NOT NULL,
   PEPAR_DESCRI         VARCHAR(20) NOT NULL,
   PRIMARY KEY (PEPAR_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_spanish_ci;

INSERT IGNORE INTO PEPAR_PAREN (PEPAR_CODIGO, PEPAR_DESCRI) VALUES
 ('P', 'Padre'), ('M', 'Madre'), ('C', 'Cónyuge'),
 ('H', 'Hijo/a'), ('E', 'Hermano/a'), ('O', 'Otro');

/* Table: PEFAM_FAMIL (FAMILIAR): un empleado puede registrar varios familiares */
CREATE TABLE IF NOT EXISTS PEFAM_FAMIL
(
   PEFAM_CODIGO         INT NOT NULL AUTO_INCREMENT,
   PEEMP_CODIGO         CHAR(10) NOT NULL,
   PEPAR_CODIGO         CHAR(1) NOT NULL,
   PEFAM_APELLI         VARCHAR(60) NOT NULL,
   PEFAM_NOMBRE         VARCHAR(60) NOT NULL,
   PEFAM_FECNAC         DATE NOT NULL,
   PRIMARY KEY (PEFAM_CODIGO),
   CONSTRAINT FK_EMP_FAM FOREIGN KEY (PEEMP_CODIGO) REFERENCES PEEMP_EMPLE (PEEMP_CODIGO)
      ON DELETE RESTRICT ON UPDATE RESTRICT,
   CONSTRAINT FK_PAR_FAM FOREIGN KEY (PEPAR_CODIGO) REFERENCES PEPAR_PAREN (PEPAR_CODIGO)
      ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_spanish_ci;

